// Storage — PostgreSQL (persistent) or atomic file fallback.
// ---------------------------------------------------------------------------
let db = null;
const STATE_CACHE_TTL_MS = 30_000;
const DATA_CACHE_TTL_MS = 5 * 60_000;
const stateReadCache = new Map();
const stateReadInFlight = new Map();
const CHUNK_CACHE_TTL_MS = 30_000;
const CHUNK_CACHE_MAX_ENTRIES = 16;
const layerChunkCache = new Map();

function clearLayerChunkCache(map) {
  const prefix = String(map || '') + '|';
  for (const key of layerChunkCache.keys()) {
    if (key.startsWith(prefix)) layerChunkCache.delete(key);
  }
}

function putLayerChunkCache(key, value) {
  layerChunkCache.set(key, { value, at: Date.now() });
  while (layerChunkCache.size > CHUNK_CACHE_MAX_ENTRIES) {
    const oldest = layerChunkCache.keys().next().value;
    if (oldest == null) break;
    layerChunkCache.delete(oldest);
  }
}

async function initDb() {
  if (!DATABASE_URL) return;
  const { Client } = require('pg');
  db = new Client({ connectionString: DATABASE_URL, ssl: { rejectUnauthorized: false } });
  await db.connect();
  await db.query(`
    CREATE TABLE IF NOT EXISTS app_state (
      key TEXT PRIMARY KEY,
      json TEXT NOT NULL,
      updated_at TEXT NOT NULL
    )
  `);
  console.log('PostgreSQL connected — state will persist across restarts');
}

const MAPS = ['comdep', 'other', 'kg'];
function mapKey(req) {
  const m = (req.query.map || '').toString();
  return MAPS.includes(m) ? m : null;
}
function stateFileFor(key) {
  return key === 'main' ? STATE_FILE : path.join(__dirname, `state.${key}.json`);
}

async function readState(key) {
  const hit = stateReadCache.get(key);
  const ttl = key === 'dataset' ? DATA_CACHE_TTL_MS : STATE_CACHE_TTL_MS;
  if (hit && Date.now() - hit.at < ttl) return hit.value;
  if (stateReadInFlight.has(key)) return stateReadInFlight.get(key);
  const pending = (async () => {
    let value = null;
    if (db) {
      try {
        // `key` is the PRIMARY KEY of app_state; concurrent reads for the same
        // map are coalesced so startup/meta/chunk requests share one DB query.
        const r = await db.query('SELECT json FROM app_state WHERE key = $1', [key]);
        value = r.rows.length ? JSON.parse(r.rows[0].json) : null;
      } catch (e) {
        console.error('DB read error:', e.message);
        value = null;
      }
    } else {
      try {
        const f = stateFileFor(key);
        if (fs.existsSync(f)) value = JSON.parse(fs.readFileSync(f, 'utf8'));
      } catch (e) {
        console.error('Failed to read state file:', e.message);
        value = null;
      }
    }
    if (value) stateReadCache.set(key, { value, at: Date.now() });
    return value;
  })();
  stateReadInFlight.set(key, pending);
  try {
    return await pending;
  } finally {
    if (stateReadInFlight.get(key) === pending) stateReadInFlight.delete(key);
  }
}

async function writeState(key, data) {
  const json = JSON.stringify(data);
  if (db) {
    await db.query(
      `INSERT INTO app_state (key, json, updated_at)
       VALUES ($1, $2, $3)
       ON CONFLICT (key) DO UPDATE SET json = $2, updated_at = $3`,
      [key, json, new Date().toISOString()]
    );
    stateReadCache.delete(key);
    return;
  }
  const f = stateFileFor(key), tmp = f + '.tmp';
  fs.writeFileSync(tmp, json, 'utf8');
  fs.renameSync(tmp, f);
  stateReadCache.delete(key);
}

function verifyKey(req) {
  if (!API_KEY) return false; // fail closed: no configured key means no writes
  const header = req.headers['x-api-key'] || '';
  return header === API_KEY;
}

function requireSession(req, res, next) {
  const user = readSession(req);
  if (!user) {
    noStore(res);
    return res.status(401).json({ error: 'Authentication required' });
  }
  req.user = user;
  next();
}

function requireAdmin(req, res, next) {
  if (!req.user || req.user.role !== 'admin') return res.status(403).json({ error: 'Owner access required' });
  next();
}

function requireMapAccess(req, res, next) {
  const map = mapKey(req);
  if (!map) return res.status(400).json({ error: 'Invalid map' });
  if (req.user.role !== 'admin' && req.user.role !== map) return res.status(403).json({ error: 'Map access denied' });
  req.map = map;
  next();
}

