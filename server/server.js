// ---------------------------------------------------------------------------
// Password and session helpers.
// Password hashes are scrypt$N$r$p$salt$hexHash strings generated by
// create-password-hash.js. Plain-text passwords never enter the repository.
// ---------------------------------------------------------------------------
function parsePasswordHash(encoded) {
  const parts = String(encoded || '').split('$');
  if (parts.length !== 6 || parts[0] !== 'scrypt') return null;
  const [, n, r, p, salt, hex] = parts;
  const N = Number(n), R = Number(r), P = Number(p);
  if (!Number.isInteger(N) || !Number.isInteger(R) || !Number.isInteger(P) || !salt || !/^[0-9a-f]+$/i.test(hex)) return null;
  return { N, R, P, salt, hex };
}

function verifyPassword(password, encoded) {
  const cfg = parsePasswordHash(encoded);
  if (!cfg) return false;
  try {
    const actual = crypto.scryptSync(String(password || ''), cfg.salt, cfg.hex.length / 2, {
      N: cfg.N, r: cfg.R, p: cfg.P, maxmem: SCRYPT_MAXMEM,
    });
    const expected = Buffer.from(cfg.hex, 'hex');
    return actual.length === expected.length && crypto.timingSafeEqual(actual, expected);
  } catch (_) {
    return false;
  }
}

// Unknown usernames must perform the same expensive password work as known
// usernames. The random hash is generated once per process and never logged or
// accepted as a real credential.
function createDummyPasswordHash() {
  const N = 16384, R = 8, P = 1, KEYLEN = 32;
  const salt = crypto.randomBytes(16).toString('hex');
  const hash = crypto.scryptSync(crypto.randomBytes(32), salt, KEYLEN, {
    N, r: R, p: P, maxmem: SCRYPT_MAXMEM,
  }).toString('hex');
  return `scrypt$${N}$${R}$${P}$${salt}$${hash}`;
}
const DUMMY_PASSWORD_HASH = createDummyPasswordHash();

function loginRateKeys(req, username) {
  const ip = String(req.ip || (req.socket && req.socket.remoteAddress) || 'unknown').slice(0, 128);
  const account = String(username || '').trim().toLowerCase().slice(0, 128) || '<empty>';
  // Keep an account bucket as well as the IP+account bucket. A managed proxy
  // can rotate the observed edge IP between requests; the account bucket keeps
  // the limiter effective without trusting a client-supplied header.
  return [`ip:${ip}|user:${account}`, `user:${account}`];
}

function pruneLoginAttempts(now = Date.now()) {
  for (const [key, entry] of loginAttempts) {
    if (entry.resetAt <= now) loginAttempts.delete(key);
  }
  while (loginAttempts.size > LOGIN_MAX_BUCKETS) {
    const first = loginAttempts.keys().next().value;
    if (first === undefined) break;
    loginAttempts.delete(first);
  }
}

function rateLimitLogin(req, res, next) {
  const now = Date.now();
  pruneLoginAttempts(now);
  const keys = loginRateKeys(req, req.body && req.body.username);
  const blocked = keys.map(key => loginAttempts.get(key)).find(entry => entry && entry.resetAt > now && entry.failures >= LOGIN_MAX_ATTEMPTS);
  if (blocked) {
    const retryAfter = Math.max(1, Math.ceil((blocked.resetAt - now) / 1000));
    noStore(res);
    res.setHeader('Retry-After', String(retryAfter));
    return res.status(429).json({ error: 'Too many login attempts', retryAfter });
  }
  req.loginRateKeys = keys;
  next();
}

function recordLoginFailure(req) {
  const now = Date.now();
  const keys = req.loginRateKeys || loginRateKeys(req, req.body && req.body.username);
  for (const key of keys) {
    const entry = loginAttempts.get(key);
    if (!entry || entry.resetAt <= now) {
      loginAttempts.set(key, { failures: 1, resetAt: now + LOGIN_WINDOW_MS, lastSeen: now });
    } else {
      entry.failures += 1;
      entry.lastSeen = now;
    }
  }
  pruneLoginAttempts(now);
}

function clearLoginFailures(req) {
  const keys = req.loginRateKeys || loginRateKeys(req, req.body && req.body.username);
  for (const key of keys) loginAttempts.delete(key);
}

function b64url(value) {
  return Buffer.from(value).toString('base64url');
}

function signSession(payload) {
  return crypto.createHmac('sha256', SESSION_SECRET).update(payload).digest('base64url');
}

function createSession(user) {
  const payload = b64url(JSON.stringify({
    u: user.username,
    role: user.role,
    iat: Date.now(),
    exp: Math.floor(Date.now() / 1000) + SESSION_TTL_SEC,
  }));
  return payload + '.' + signSession(payload);
}

function readCookie(req, name) {
  const raw = req.headers.cookie || '';
  for (const part of raw.split(';')) {
    const i = part.indexOf('=');
    if (i < 0) continue;
    if (part.slice(0, i).trim() === name) {
      try { return decodeURIComponent(part.slice(i + 1).trim()); } catch (_) { return ''; }
    }
  }
  return '';
}

function readBearer(req) {
  const header = String(req.headers.authorization || '');
  return /^Bearer\s+/i.test(header) ? header.slice(7).trim() : '';
}

function verifySessionToken(token) {
  if (!SESSION_SECRET || !token) return null;
  const dot = token.indexOf('.');
  if (dot <= 0) return null;
  const payload = token.slice(0, dot), signature = token.slice(dot + 1);
  const expected = signSession(payload);
  const a = Buffer.from(signature), b = Buffer.from(expected);
  if (a.length !== b.length || !crypto.timingSafeEqual(a, b)) return null;
  try {
    const data = JSON.parse(Buffer.from(payload, 'base64url').toString('utf8'));
    if (!data.u || !data.role || !Number.isFinite(data.exp) || data.exp <= Date.now() / 1000) return null;
    const user = AUTH_USERS.get(String(data.u).toLowerCase());
    if (!user || user.role !== data.role) return null;
    // Смена пароля отзывает все сессии, выданные до неё.
    const issuedAt = Number.isFinite(data.iat) ? data.iat : (data.exp - SESSION_TTL_SEC) * 1000;
    if (user.changedAt && issuedAt < user.changedAt) return null;
    return { username: user.username, role: user.role };
  } catch (_) {
    return null;
  }
}

function sessionTokenFromReq(req) {
  const bearer = readBearer(req);
  if (bearer && verifySessionToken(bearer)) return bearer;
  const cookie = readCookie(req, 'hm_session');
  return cookie && verifySessionToken(cookie) ? cookie : '';
}

function readSession(req) {
  // Prefer the explicit bearer token for GitHub Pages ↔ Render, then fall back
  // to the HttpOnly cookie for same-site or browsers that retain third-party cookies.
  return verifySessionToken(readBearer(req)) || verifySessionToken(readCookie(req, 'hm_session'));
}

// Ключ записи, привязанный к конкретной сессии. Владелец больше не вводит его
// руками: он выдаётся при входе и при восстановлении сессии. Значение нельзя
// вычислить без SESSION_SECRET, поэтому заголовок остаётся защитой от CSRF —
// чужая страница не сможет его подставить, даже если браузер пошлёт cookie.
function writeTokenFor(sessionToken) {
  if (!SESSION_SECRET || !sessionToken) return '';
  return crypto.createHmac('sha256', SESSION_SECRET)
    .update('write|').update(sessionToken).digest('base64url').slice(0, 43);
}

function isHttps(req) {
  return req.secure || req.headers['x-forwarded-proto'] === 'https' || process.env.NODE_ENV === 'production';
}

// Атрибуты куки сессии живут в одном месте: выдача и сброс обязаны совпадать,
// иначе браузер не сочтёт сброс той же кукой.
function writeSessionCookie(req, res, value, maxAge) {
  const attrs = isHttps(req) ? 'SameSite=None; Secure' : 'SameSite=Lax';
  res.setHeader('Set-Cookie', `hm_session=${value}; Max-Age=${maxAge}; Path=/; HttpOnly; ${attrs}`);
}

function setSessionCookie(req, res, token) {
  writeSessionCookie(req, res, encodeURIComponent(token), SESSION_TTL_SEC);
}

function clearSessionCookie(req, res) {
  writeSessionCookie(req, res, '', 0);
}

function noStore(res) {
  res.setHeader('Cache-Control', 'no-store');
}

