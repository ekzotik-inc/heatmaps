    ...m, name: cleanText(m.name, 60) || m.id, desc: cleanText(m.desc, 120), icon: cleanIcon(m.icon, '🗺'),
    country: MAP_COUNTRIES.has(m.country) ? m.country : 'uz', viewers: cleanViewers(m.viewers),
