  origin: (origin, cb) => {
    if (!origin) return cb(null, true);
    if (ORIGINS.length === 0 || ORIGINS.includes(origin)) return cb(null, origin);
    cb(new Error(`CORS: origin ${origin} not allowed`));
  },
  credentials: true,
