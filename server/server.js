function pruneStateCache() {
  const now = Date.now();
  for (const [k, v] of stateReadCache) {
    if (now - v.at >= stateCacheTtl(k)) stateReadCache.delete(k);
  }
  for (const [k, v] of layerChunkCache) {
    if (now - v.at >= CHUNK_CACHE_TTL_MS) layerChunkCache.delete(k);
  }
}
